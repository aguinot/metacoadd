def _make_exposure(shape, crpix, include_noise=True):
    """Build an Exposure with deterministic image layers."""
    image = np.arange(
        1,
        np.prod(shape) + 1,
        dtype=np.float64,
    ).reshape(shape)
    weight = np.full(shape, 4.0)

    noise = np.full(shape, 0.5) if include_noise else None

    return Exposure(
        image=image,
        weight=weight,
        noise=noise,
        wcs=_make_astropy_wcs(crpix=crpix),
    )


def _assert_jacobian_matches_exposure(obs, exposure):
    """Check the ngmix Jacobian against the image WCS."""
    expected_row = (exposure.image.array.shape[0] - 1) / 2
    expected_col = (exposure.image.array.shape[1] - 1) / 2

    np.testing.assert_allclose(
        obs.jacobian.get_cen(),
        (expected_row, expected_col),
    )

    # GalSim image coordinates are one-based, so true_center is the
    # appropriate position at which to evaluate the WCS Jacobian.
    expected = exposure.wcs.jacobian(
        image_pos=exposure.image.true_center,
    )

    np.testing.assert_allclose(
        [
            obs.jacobian.dudcol,
            obs.jacobian.dudrow,
            obs.jacobian.dvdcol,
            obs.jacobian.dvdrow,
        ],
        [
            expected.dudx,
            expected.dudy,
            expected.dvdx,
            expected.dvdy,
        ],
        rtol=1.0e-10,
        atol=1.0e-12,
    )


def test_exp2obs():
    """Test conversion of real galaxy and PSF exposures."""
    exposure = _make_exposure(
        shape=(9, 13),
        crpix=(7.0, 5.0),
    )
    psf_exposure = _make_exposure(
        shape=(7, 11),
        crpix=(6.0, 4.0),
        include_noise=False,
    )

    obs = _exp2obs(
        exposure,
        exp_psf=psf_exposure,
    )

    assert isinstance(obs, ngmix.Observation)
    assert obs.has_psf()

    np.testing.assert_array_equal(
        obs.image,
        exposure.image.array,
    )
    np.testing.assert_array_equal(
        obs.weight,
        exposure.weight.array,
    )
    np.testing.assert_array_equal(
        obs.noise,
        exposure.noise.array,
    )
    np.testing.assert_array_equal(
        obs.bmask,
        np.zeros_like(obs.image, dtype=np.int32),
    )
    np.testing.assert_array_equal(
        obs.ormask,
        np.zeros_like(obs.image, dtype=np.int32),
    )

    np.testing.assert_array_equal(
        obs.psf.image,
        psf_exposure.image.array,
    )
    np.testing.assert_array_equal(
        obs.psf.weight,
        psf_exposure.weight.array,
    )

    _assert_jacobian_matches_exposure(
        obs,
        exposure,
    )
    _assert_jacobian_matches_exposure(
        obs.psf,
        psf_exposure,
    )


