def test_exp2obs_without_optional_maps():
    """Test default handling of missing weight and noise maps."""
    image = np.arange(
        81,
        dtype=np.float64,
    ).reshape(9, 9)

    psf_image = np.arange(
        49,
        dtype=np.float64,
    ).reshape(7, 7)

    # Do not provide weight or noise maps.
    exposure = Exposure(
        image=image,
        wcs=_make_astropy_wcs(
            crpix=(5.0, 5.0),
        ),
    )
    psf_exposure = Exposure(
        image=psf_image,
        wcs=_make_astropy_wcs(
            crpix=(4.0, 4.0),
        ),
    )

    obs = _exp2obs(
        exposure,
        exp_psf=psf_exposure,
    )

    # ngmix replaces weight=None with a unit-weight map.
    np.testing.assert_array_equal(
        obs.weight,
        np.ones_like(image),
    )
    np.testing.assert_array_equal(
        obs.psf.weight,
        np.ones_like(psf_image),
    )

    # Unlike the weight, a missing noise map remains unset.
    assert not obs.has_noise()

    np.testing.assert_array_equal(
        obs.image,
        image,
    )
    np.testing.assert_array_equal(
        obs.psf.image,
        psf_image,
    )


def test_atleast_mbobs():
    """Test conversion of all supported observation containers."""
    obs = ngmix.Observation(
        image=np.ones((5, 5)),
    )

    from_obs = atleast_mbobs(obs)

    assert isinstance(from_obs, ngmix.MultiBandObsList)
    assert len(from_obs) == 1
    assert len(from_obs[0]) == 1
    assert from_obs[0][0] is obs

    obslist = ngmix.ObsList()
    obslist.append(obs)

    from_obslist = atleast_mbobs(obslist)

    assert isinstance(from_obslist, ngmix.MultiBandObsList)
    assert len(from_obslist) == 1
    assert from_obslist[0] is obslist

    mbobs = ngmix.MultiBandObsList()
    mbobs.append(obslist)

    from_mbobs = atleast_mbobs(mbobs)

    assert from_mbobs is mbobs

    with pytest.raises(
        ValueError,
        match="obs must be an Observation",
    ):
        atleast_mbobs(object())


def test_identity_njit():
    """Test direct and configured decorator forms."""

    def function(value):
        return value + 1

    direct = _identity_njit(function)

    assert direct is function
    assert direct(2) == 3

    configured = _identity_njit(
        cache=True,
        fastmath=True,
    )
    decorated = configured(function)

    assert decorated is function
    assert decorated(2) == 3
