def _make_astropy_wcs(crpix=(1024.5, 2048.5)):
    """Build a rotated celestial WCS with a small SIP distortion."""
    scale = 0.2 / 3600.0
    angle = np.deg2rad(23.0)

    wcs = WCS(naxis=2)
    wcs.wcs.crpix = np.asarray(crpix, dtype=np.float64)
    wcs.wcs.crval = [150.0, 2.0]
    wcs.wcs.ctype = [
        "RA---TAN-SIP",
        "DEC--TAN-SIP",
    ]
    wcs.wcs.cunit = ["deg", "deg"]
    wcs.wcs.cd = scale * np.array(
        [
            [-np.cos(angle), np.sin(angle)],
            [np.sin(angle), np.cos(angle)],
        ]
    )

    a = np.zeros((4, 4))
    b = np.zeros((4, 4))

    a[2, 0] = 2.0e-8
    a[1, 1] = -1.0e-8
    b[0, 2] = -1.5e-8
    b[1, 1] = 0.8e-8

    wcs.sip = Sip(
        a,
        b,
        None,
        None,
        wcs.wcs.crpix,
    )

    return wcs


@pytest.mark.coverage_all_params
@pytest.mark.parametrize(
    "use_astropy_attribute",
    [False, True],
)
def test_shift_wcs_preserves_sky_coordinates(
    use_astropy_attribute,
):
    """
    Check that a cutout pixel maps to the same sky position as its
    corresponding parent-image pixel.

    If the cutout begins at parent pixel (xmin, ymin), then cutout
    pixel (1, 1) must represent parent pixel (xmin, ymin).
    """
    astropy_wcs = _make_astropy_wcs()
    original_wcs = galsim.AstropyWCS(wcs=astropy_wcs)

    # Exercise both supported paths in shift_wcs.
    if use_astropy_attribute:
        original_wcs.astropy = astropy_wcs

    original_crpix = astropy_wcs.wcs.crpix.copy()

    offset = galsim.PositionI(
        x=1001,
        y=2001,
    )
    shifted_wcs = shift_wcs(
        original_wcs,
        offset,
    )

    expected_crpix = original_crpix - np.array(
        [
            offset.x - 1,
            offset.y - 1,
        ]
    )

    np.testing.assert_allclose(
        shifted_wcs.wcs.wcs.crpix,
        expected_crpix,
        rtol=0.0,
        atol=1.0e-12,
    )

    # shift_wcs must not modify the input WCS.
    np.testing.assert_array_equal(
        astropy_wcs.wcs.crpix,
        original_crpix,
    )

    cutout_pixels = np.array(
        [
            [1.0, 1.0],
            [24.5, 48.5],
            [73.25, 81.75],
        ]
    )
    parent_pixels = cutout_pixels + np.array(
        [
            offset.x - 1,
            offset.y - 1,
        ]
    )

    parent_world = astropy_wcs.all_pix2world(
        parent_pixels,
        1,
    )
    cutout_world = shifted_wcs.wcs.all_pix2world(
        cutout_pixels,
        1,
    )

    parent_sky = SkyCoord(
        parent_world[:, 0] * u.deg,
        parent_world[:, 1] * u.deg,
    )
    cutout_sky = SkyCoord(
        cutout_world[:, 0] * u.deg,
        cutout_world[:, 1] * u.deg,
    )

    separation = parent_sky.separation(cutout_sky)

    # This is much smaller than any relevant astrometric tolerance.
    assert np.all(separation < 1.0e-5 * u.arcsec)

    # Verify the inverse transformation independently.
    parent_pixels_recovered = astropy_wcs.all_world2pix(
        parent_world,
        1,
    )
    cutout_pixels_recovered = shifted_wcs.wcs.all_world2pix(
        parent_world,
        1,
    )

    pixel_shift = np.array(
        [
            offset.x - 1,
            offset.y - 1,
        ],
        dtype=np.float64,
    )

    expected_pixel_shifts = np.broadcast_to(
        pixel_shift,
        parent_pixels_recovered.shape,
    )

    np.testing.assert_allclose(
        parent_pixels_recovered - cutout_pixels_recovered,
        expected_pixel_shifts,
        rtol=0.0,
        atol=1.0e-7,
    )

    # Shifting the reference pixel must preserve the local scale,
    # rotation, shear, and distortion at corresponding positions.
    for cutout_pixel, parent_pixel in zip(
        cutout_pixels,
        parent_pixels,
        strict=False,
    ):
        original_jacobian = original_wcs.jacobian(
            image_pos=galsim.PositionD(
                x=parent_pixel[0],
                y=parent_pixel[1],
            )
        )
        shifted_jacobian = shifted_wcs.jacobian(
            image_pos=galsim.PositionD(
                x=cutout_pixel[0],
                y=cutout_pixel[1],
            )
        )

        original_matrix = np.array(
            [
                original_jacobian.dudx,
                original_jacobian.dudy,
                original_jacobian.dvdx,
                original_jacobian.dvdy,
            ]
        )
        shifted_matrix = np.array(
            [
                shifted_jacobian.dudx,
                shifted_jacobian.dudy,
                shifted_jacobian.dvdx,
                shifted_jacobian.dvdy,
            ]
        )

        np.testing.assert_allclose(
            shifted_matrix,
            original_matrix,
            rtol=1.0e-7,
            atol=1.0e-10,
        )


def test_shift_wcs_identity():
    """Check that offset (1, 1) leaves the pixel mapping unchanged."""
    astropy_wcs = _make_astropy_wcs()
    original_wcs = galsim.AstropyWCS(wcs=astropy_wcs)

    shifted_wcs = shift_wcs(
        original_wcs,
        galsim.PositionI(1, 1),
    )

    pixels = np.array(
        [
            [1.0, 1.0],
            [100.5, 200.5],
            [1024.5, 2048.5],
        ]
    )

    original_world = astropy_wcs.all_pix2world(
        pixels,
        1,
    )
    shifted_world = shifted_wcs.wcs.all_pix2world(
        pixels,
        1,
    )

    np.testing.assert_allclose(
        shifted_world,
        original_world,
        rtol=0.0,
        atol=1.0e-10,
    )


