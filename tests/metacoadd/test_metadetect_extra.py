def test_go_without_multiband_coadd():
    """Run real detection using only the first observation."""
    mcal_config = MCAL_CONFIG.copy()
    mcal_config["types"] = ["noshear"]

    mbobs = _make_mbobs()
    shape = mbobs[0][0].image.shape

    mbobs[0][0].set_bmask(
        np.full(
            shape,
            1,
            dtype=np.int32,
        )
    )
    mbobs[1][0].set_bmask(
        np.full(
            shape,
            2,
            dtype=np.int32,
        )
    )
    mbobs[0][0].set_ormask(
        np.full(
            shape,
            4,
            dtype=np.int32,
        )
    )
    mbobs[1][0].set_ormask(
        np.full(
            shape,
            8,
            dtype=np.int32,
        )
    )

    md = _make_md(
        coadd_multiband=False,
        mcal_config=mcal_config,
        detect_thresh=5.0,
        detect_kernel=[[1.0]],
    )

    result = md.go(mbobs)

    assert set(result) == {"noshear"}

    catalog = result["noshear"]
    assert catalog.size > 0

    # Only the first observation supplies the detection masks.
    assert np.all((catalog["bmask"] & 1) == 1)
    assert np.all((catalog["bmask"] & 2) == 0)
    assert np.all((catalog["ormask"] & 4) == 4)
    assert np.all((catalog["ormask"] & 8) == 0)

    _assert_successful_measurements(
        catalog,
        model="wmom",
        nband=2,
    )


def test_go_original_and_imcom_catalogs():
    """Run the real reference and placeholder branches."""
    mcal_config = MCAL_CONFIG.copy()
    mcal_config["types"] = [
        "noshear",
        "1p",
    ]

    original_config = {
        "mcal_type_ref": "noshear",
        "wmom_fwhm": 0.5,
        "psf_fitter": "wmom",
    }
    imcom_config = {
        "mcal_type_ref": "noshear",
        "layers": {
            "Coverage": {
                "combine": "mean",
                "stat": "std",
            },
        },
    }

    mbobs = _make_mbobs()
    _add_imcom_layers(mbobs)

    md = _make_md(
        mcal_config=mcal_config,
        original_image_config=original_config,
        imcom_map_config=imcom_config,
        do_uberseg=True,
        detect_thresh=5.0,
        detect_kernel=[[1.0]],
    )

    result = md.go(mbobs)

    assert set(result) == {
        "noshear",
        "1p",
    }
    assert result["noshear"].size > 0
    assert result["1p"].size > 0

    for band_index in range(2):
        flags_name = f"original_flags_{band_index}"
        flux_name = f"original_flux_{band_index}"

        assert np.any(result["noshear"][flags_name] != 42)
        assert np.all(result["1p"][flags_name] == 42)

        good = result["noshear"][flags_name] == 0
        if np.any(good):
            assert np.all(np.isfinite(result["noshear"][flux_name][good]))

        mean_name = f"IMCOM_Coverage_mean_{band_index}"
        std_name = f"IMCOM_Coverage_std_{band_index}"

        np.testing.assert_allclose(
            result["noshear"][mean_name],
            band_index + 1.0,
        )
        np.testing.assert_allclose(
            result["noshear"][std_name],
            0.0,
        )

        # Non-reference branches contain the real
        # get_output_imcom_map_cat sentinel.
        np.testing.assert_allclose(
            result["1p"][mean_name],
            -10.0,
        )
        np.testing.assert_allclose(
            result["1p"][std_name],
            -10.0,
        )
