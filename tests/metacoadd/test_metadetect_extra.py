import ngmix

from galsim_sim import _get_obs
from metacoadd.metadetect import MetaDetect


MCAL_TYPES = [
    "noshear",
    "1p",
    "1m",
    "2p",
    "2m",
]

MCAL_CONFIG = {
    "step": 0.01,
    "types": MCAL_TYPES,
    "psf": "fitgauss",
    "use_noise_image": True,
    "fixnoise": True,
    "has_pixel": False,
}


def _make_mbobs(nband=2, seed=10):
    """Build deterministic multiband observations."""
    mbobs = ngmix.MultiBandObsList()

    for band_index in range(nband):
        obs = _get_obs(
            np.random.RandomState(seed + band_index),
            noise=1.0e-4,
            set_noise_image=True,
            n=35,
        )
        obs.set_ormask(
            np.zeros_like(
                obs.image,
                dtype=np.int32,
            )
        )

        obslist = ngmix.ObsList()
        obslist.append(obs)
        mbobs.append(obslist)

    return mbobs


def _make_md(**kwargs):
    """Build a MetaDetect instance with a complete configuration."""
    config = {
        "rng": np.random.RandomState(20),
        "models": ["wmom"],
        "fwhms": [1.2],
        "symmetrizes": [True],
        "stamp_size": 35,
        "coadd_fscale": [[1.0], [1.0]],
        "mcal_config": MCAL_CONFIG.copy(),
    }
    config.update(kwargs)
    return MetaDetect(**config)


def _add_imcom_layers(mbobs):
    """Attach deterministic coverage maps to the observations."""
    for band_index, obslist in enumerate(mbobs):
        for obs in obslist:
            obs.coverage = np.full(
                obs.image.shape,
                band_index + 1.0,
                dtype=np.float64,
            )


def _assert_successful_measurements(catalog, model, nband):
    """Check that a real fitter produced useful measurements."""
    flags_name = f"{model}_flags"

    assert flags_name in catalog.dtype.names
    assert f"{model}_T" in catalog.dtype.names
    assert f"{model}_g1" in catalog.dtype.names
    assert f"{model}_g2" in catalog.dtype.names

    successful = catalog[flags_name] == 0
    assert np.any(successful)

    fields = [
        f"{model}_T",
        f"{model}_Tpsf",
        f"{model}_s2n",
        f"{model}_g1",
        f"{model}_g2",
    ]

    for band_index in range(nband):
        fields.extend(
            [
                f"{model}_flux_{band_index}",
                f"{model}_flux_err_{band_index}",
            ]
        )

    for field in fields:
        assert field in catalog.dtype.names
        assert np.all(np.isfinite(catalog[field][successful]))


