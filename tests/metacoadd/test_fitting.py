class _SequenceFitter:
    """Return a predefined sequence of fitter results."""

    def __init__(self, flags):
        self.flags = iter(flags)
        self.calls = []

    def go(self, obs, guess):
        """Record the call and return the next result."""
        self.calls.append((obs, np.array(guess, copy=True)))
        return {"flags": next(self.flags)}


