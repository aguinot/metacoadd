def test_bootstrap_guess(monkeypatch):
    """Test PSF fitting, failed-PSF removal, and guess forwarding."""
    obs = object()
    filtered_obs = object()
    guess = np.arange(6, dtype="f8")
    expected = {"flags": 0}

    runner = Mock()
    runner.go.return_value = expected
    psf_runner = Mock()

    remove_failed = Mock(return_value=filtered_obs)
    monkeypatch.setattr(
        fitting,
        "remove_failed_psf_obs",
        remove_failed,
    )

    bootstrapper = BootstrapperGuess(
        runner=runner,
        psf_runner=psf_runner,
        ignore_failed_psf=True,
    )
    res = bootstrapper.go(obs, guess=guess)

    assert res is expected
    psf_runner.go.assert_called_once_with(obs=obs)
    remove_failed.assert_called_once_with(obs=obs)
    runner.go.assert_called_once_with(
        obs=filtered_obs,
        guess=guess,
    )

    runner.reset_mock()
    psf_runner.reset_mock()
    remove_failed.reset_mock()

    bootstrapper = BootstrapperGuess(
        runner=runner,
        psf_runner=psf_runner,
        ignore_failed_psf=False,
    )
    res = bootstrapper.go(obs, guess=guess)

    assert res is expected
    psf_runner.go.assert_called_once_with(obs=obs)
    remove_failed.assert_not_called()
    runner.go.assert_called_once_with(
        obs=obs,
        guess=guess,
    )

    runner.reset_mock()
    psf_runner.reset_mock()

    res = bootstrap_guess(
        obs=obs,
        runner=runner,
        guess=guess,
        psf_runner=None,
    )

    assert res is expected
    psf_runner.go.assert_not_called()
    runner.go.assert_called_once_with(
        obs=obs,
        guess=guess,
    )


