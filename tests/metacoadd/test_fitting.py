    assert res["flags"] == 0
    assert len(fitter.calls) == 2
    assert guesser.call_count == 2
    np.testing.assert_array_equal(
        fitter.calls[0][1],
        np.arange(6),
    )
    np.testing.assert_array_equal(
        fitter.calls[1][1],
        np.arange(6) + 1,
    )

    fitter = _SequenceFitter(flags=[1, 0])
    guesser = Mock()
    runner = RunnerGuess(
        fitter=fitter,
        guesser=guesser,
        ntry=3,
    )
    guess = np.arange(6, dtype="f8")

    res = runner.go(obs, guess=guess)

    assert res["flags"] == 0
    assert len(fitter.calls) == 2
    guesser.assert_not_called()

    for _, used_guess in fitter.calls:
        np.testing.assert_array_equal(used_guess, guess)


