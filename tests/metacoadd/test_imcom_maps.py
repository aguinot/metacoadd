import numpy as np
import pytest

import ngmix

from metacoadd.imcom_maps import (
    extract_imcom_maps,
    get_combine_func,
    get_imcom_map_cat_dtype,
    get_output_imcom_map_cat,
    get_stat_func,
)


SHAPE = (3, 3)

SEG_MAP = np.asarray(
    [
        [0, 1, 1],
        [1, 2, 2],
        [2, 0, 0],
    ],
    dtype=np.int32,
)

IMCOM_MAP_CONFIG = {
    "MeanMap": {},
    "MedianMap": {
        "combine": "median",
        "stat": "mad",
    },
    "SumMap": {
        "combine": "sum",
        "stat": "var",
    },
    "MinMap": {
        "combine": "min",
        "stat": "std",
    },
    "MaxMap": {
        "combine": "max",
        "stat": "std",
    },
}


def _make_mbobs(layer_names=None):
    """Build two bands containing deterministic IMCOM map layers."""
    if layer_names is None:
        layer_names = IMCOM_MAP_CONFIG

    mbobs = ngmix.MultiBandObsList()

    for band_index in range(2):
        values = (
            np.arange(np.prod(SHAPE), dtype=np.float64).reshape(SHAPE)
            + 10 * band_index
        )
        obs = ngmix.Observation(
            image=np.zeros(SHAPE, dtype=np.float64),
            weight=np.ones(SHAPE, dtype=np.float64),
        )

        for layer_name in layer_names:
            setattr(
                obs,
                layer_name.lower(),
                values.copy(),
            )

        obslist = ngmix.ObsList()
        obslist.append(obs)
        mbobs.append(obslist)

    return mbobs


def _make_sep_cat(n_obj=2):
    """Build a minimal detection catalog."""
    sep_cat = np.zeros(
        n_obj,
        dtype=[
            ("number", np.int32),
            ("x", np.float64),
            ("y", np.float64),
        ],
    )
    sep_cat["number"] = np.arange(1, n_obj + 1)
    return sep_cat


