def test_extract_imcom_maps():
    """Test extraction of all supported statistics in two bands."""
    mbobs = _make_mbobs()
    sep_cat = _make_sep_cat()

    output = extract_imcom_maps(
        mbobs=mbobs,
        sep_cat=sep_cat,
        seg_map=SEG_MAP,
        config={"layers": IMCOM_MAP_CONFIG},
    )

    assert output.shape == (2,)

    expected_std = np.sqrt(2.0 / 3.0)
    expected_var = 2.0 / 3.0

    for band_index in range(2):
        shift = 10.0 * band_index

        np.testing.assert_allclose(
            output[f"IMCOM_MeanMap_mean_{band_index}"],
            np.asarray([2.0, 5.0]) + shift,
        )
        np.testing.assert_allclose(
            output[f"IMCOM_MeanMap_std_{band_index}"],
            [expected_std, expected_std],
        )

        np.testing.assert_allclose(
            output[f"IMCOM_MedianMap_median_{band_index}"],
            np.asarray([2.0, 5.0]) + shift,
        )
        np.testing.assert_allclose(
            output[f"IMCOM_MedianMap_mad_{band_index}"],
            [1.0, 1.0],
        )

        np.testing.assert_allclose(
            output[f"IMCOM_SumMap_sum_{band_index}"],
            np.asarray([6.0, 15.0]) + 3.0 * shift,
        )
        np.testing.assert_allclose(
            output[f"IMCOM_SumMap_var_{band_index}"],
            [expected_var, expected_var],
        )

        np.testing.assert_allclose(
            output[f"IMCOM_MinMap_min_{band_index}"],
            np.asarray([1.0, 4.0]) + shift,
        )
        np.testing.assert_allclose(
            output[f"IMCOM_MinMap_std_{band_index}"],
            [expected_std, expected_std],
        )

        np.testing.assert_allclose(
            output[f"IMCOM_MaxMap_max_{band_index}"],
            np.asarray([3.0, 6.0]) + shift,
        )
        np.testing.assert_allclose(
            output[f"IMCOM_MaxMap_std_{band_index}"],
            [expected_std, expected_std],
        )


